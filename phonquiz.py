"""
Практика фонетики (версия 27): слоги для упражнений в Mini App.

Берём только иероглифы с одним устойчивым чтением (без «хитрых» многозвучных), чтобы озвучка и пиньинь всегда совпадали.
Упражнения: «услышь и выбери тон» и «скажи» (проверка голосом, как в карточке иероглифа).
"""
import random

# тон → [(иероглиф, пиньинь)]
SYLLABLES = {
    1: [("妈", "mā"), ("八", "bā"), ("书", "shū"), ("衣", "yī"), ("他", "tā"), ("家", "jiā"), ("天", "tiān"), ("吃", "chī"),
        ("听", "tīng"), ("说", "shuō"), ("星", "xīng"), ("山", "shān"), ("飞", "fēi"), ("开", "kāi")],
    2: [("麻", "má"), ("人", "rén"), ("学", "xué"), ("来", "lái"), ("回", "huí"), ("茶", "chá"), ("明", "míng"), ("年", "nián"),
        ("能", "néng"), ("红", "hóng"), ("姨", "yí"), ("拔", "bá"), ("河", "hé")],
    3: [("马", "mǎ"), ("你", "nǐ"), ("我", "wǒ"), ("九", "jiǔ"), ("五", "wǔ"), ("水", "shuǐ"), ("手", "shǒu"), ("有", "yǒu"),
        ("买", "mǎi"), ("请", "qǐng"), ("酒", "jiǔ"), ("把", "bǎ"), ("椅", "yǐ")],
    4: [("骂", "mà"), ("爸", "bà"), ("树", "shù"), ("是", "shì"), ("去", "qù"), ("看", "kàn"), ("大", "dà"), ("四", "sì"),
        ("六", "liù"), ("要", "yào"), ("做", "zuò"), ("住", "zhù"), ("菜", "cài"), ("贵", "guì")],
}


def pool():
    return [{"c": c, "py": py, "tone": t} for t, items in SYLLABLES.items() for c, py in items]


def make(n=10, rng=None):
    """n слогов, тоны перемешаны поровну, без повторов иероглифов."""
    rng = rng or random
    n = max(1, min(int(n), 20))
    per = {t: rng.sample(items, len(items)) for t, items in SYLLABLES.items()}
    out, t = [], 1
    order = [1, 2, 3, 4]
    rng.shuffle(order)
    i = 0
    while len(out) < n:
        tone = order[i % 4]
        i += 1
        if per[tone]:
            c, py = per[tone].pop()
            out.append({"c": c, "py": py, "tone": tone})
    rng.shuffle(out)
    return out
